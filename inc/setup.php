<?php
declare(strict_types=1);

/*
 * Setup token for the web installer.
 *
 * Before the app is configured, anyone who can reach the site could otherwise run
 * the installer and set the admin password ("installer takeover"). The installer
 * therefore only accepts a submission with the setup token, which is
 *   - taken from the environment variable W2B_SETUP_TOKEN, or
 *   - generated on first use, stored in <data dir>/.setup_token (mode 0600) and
 *     written to the PHP error log / container log.
 * Optionally, requests from the loopback interface may skip the token when
 * W2B_SETUP_ALLOW_LOCAL=1 is set (handy for `php -S 127.0.0.1:8080` — do NOT enable
 * it behind a reverse proxy running on the same host).
 */

function setup_token_file(): string
{
    return w2b_data_dir() . '/.setup_token';
}

/** The token the installer expects, creating (and logging) one if necessary. Null if none can be stored. */
function setup_ensure_token(bool $log = true): ?string
{
    $env = w2b_env('W2B_SETUP_TOKEN');
    if ($env !== null) {
        return $env;
    }
    $file = setup_token_file();
    if (is_file($file)) {
        $t = trim((string) @file_get_contents($file));
        if ($t !== '') {
            return $t;
        }
    }
    $dir = dirname($file);
    if (!is_dir($dir)) {
        @mkdir($dir, 0770, true);
    }
    $token = token_new(24);
    $old = umask(0077);
    $ok = @file_put_contents($file, $token . "\n", LOCK_EX);
    umask($old);
    if ($ok === false) {
        return null;
    }
    @chmod($file, 0600);
    if ($log) {
        error_log(setup_banner($token));
    }
    return $token;
}

function setup_banner(string $token): string
{
    return "What2Bring setup token: {$token}  (enter it in the web installer; also stored in "
        . setup_token_file() . ')';
}

function setup_token_valid(string $given): bool
{
    $expected = setup_ensure_token(false);
    return $expected !== null && $given !== '' && hash_equals($expected, trim($given));
}

/** Loopback request with W2B_SETUP_ALLOW_LOCAL=1 → token not required. */
function setup_local_bypass(): bool
{
    if (w2b_env_bool('W2B_SETUP_ALLOW_LOCAL') !== true) {
        return false;
    }
    $remote = (string) ($_SERVER['REMOTE_ADDR'] ?? '');
    return $remote === '127.0.0.1' || $remote === '::1';
}

function setup_finish(): void
{
    @unlink(setup_token_file());
}

/** PHP single-quoted string literal. */
function w2b_php_str(string $v): string
{
    return "'" . addcslashes($v, "\\'") . "'";
}

/**
 * Render the config.php written by the installer.
 * $v keys: hash, pepper, base_url, lang, dry_run, trusted_proxies (string[]), smtp (array).
 */
function setup_render_config(array $v, string $cfgFile): string
{
    $s = $v['smtp'];
    $standardLayout = dirname($cfgFile) === dirname(__DIR__) && w2b_env('W2B_DATA_DIR') === null;
    $dbLine = $standardLayout
        ? "    'db_file' => __DIR__ . '/data/what2bring.sqlite',\n"
        : "    // 'db_file' => '/path/to/what2bring.sqlite',   // default: <W2B_DATA_DIR>/what2bring.sqlite\n";
    $proxies = implode(', ', array_map('w2b_php_str', $v['trusted_proxies']));
    return "<?php\n// What2Bring configuration — generated by the web installer. Keep private, do not commit.\n"
        . "// Every value can also be overridden by an environment variable (see README).\n"
        . "return [\n"
        . "    'admin_password_hash' => " . w2b_php_str($v['hash']) . ",\n"
        . "    'app_pepper' => " . w2b_php_str($v['pepper']) . ",\n"
        . "    'base_url' => " . w2b_php_str($v['base_url']) . ",\n"
        . "    'default_lang' => " . w2b_php_str($v['lang']) . ",\n"
        . $dbLine
        . "    'mail_dry_run' => " . ($v['dry_run'] ? 'true' : 'false') . ",\n"
        . "    // Dry-run mail log: 'redacted' (recipient masked), 'full' or 'off'.\n"
        . "    'mail_log' => 'redacted',\n"
        . "    // Reverse proxies allowed to set X-Forwarded-For / X-Forwarded-Proto (IPs or CIDRs).\n"
        . "    'trusted_proxies' => [" . $proxies . "],\n"
        . "    // Admin is logged out after this many seconds of inactivity.\n"
        . "    'admin_idle_timeout' => 1800,\n"
        . "    // Delete polls N days after their date (0 = never).\n"
        . "    'purge_after_days' => 0,\n"
        . "    'smtp' => [\n"
        . "        'host' => " . w2b_php_str($s['host']) . ",\n"
        . "        'port' => " . (int) $s['port'] . ",\n"
        . "        'secure' => " . w2b_php_str($s['secure']) . ",\n"
        . "        'user' => " . w2b_php_str($s['user']) . ",\n"
        . "        'pass' => " . w2b_php_str($s['pass']) . ",\n"
        . "        'from_email' => " . w2b_php_str($s['from_email']) . ",\n"
        . "        'from_name' => " . w2b_php_str($s['from_name']) . ",\n"
        . "        'timeout' => 15,\n"
        . "        'verify_tls' => true,\n"
        . "    ],\n];\n";
}
